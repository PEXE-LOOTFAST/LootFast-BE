CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    first_name VARCHAR(10) NOT NULL,
    last_name VARCHAR(20) NOT NULL,
    phone_number VARCHAR(9) NOT NULL,
    role VARCHAR(255) NOT NULL,
    status VARCHAR(32),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Databases created before email verification do not have these columns.
-- Existing accounts were already allowed to sign in, so preserve that behavior.
ALTER TABLE users ADD COLUMN IF NOT EXISTS public_id UUID;
ALTER TABLE users ADD COLUMN IF NOT EXISTS status VARCHAR(32);

UPDATE users
SET public_id = gen_random_uuid()
WHERE public_id IS NULL;

UPDATE users
SET status = 'VERIFIED'
WHERE status IS NULL;

ALTER TABLE users ALTER COLUMN public_id SET NOT NULL;
ALTER TABLE users ALTER COLUMN status SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uk_users_public_id ON users (public_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_users_email ON users (email);
CREATE UNIQUE INDEX IF NOT EXISTS uk_users_phone_number ON users (phone_number);
