CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,
    recipient_user_id BIGINT NOT NULL,
    type VARCHAR(32) NOT NULL,
    match_reason VARCHAR(32),
    deal_public_id UUID NOT NULL,
    store_public_id UUID NOT NULL,
    title VARCHAR(160) NOT NULL,
    message VARCHAR(500) NOT NULL,
    image_url VARCHAR(2048),
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_notifications_public_id UNIQUE (public_id),
    CONSTRAINT uk_notifications_recipient_type_deal
        UNIQUE (recipient_user_id, type, deal_public_id),
    CONSTRAINT fk_notifications_recipient
        FOREIGN KEY (recipient_user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT ck_notifications_type
        CHECK (type IN ('MATCHING_DEAL')),
    CONSTRAINT ck_notifications_match_reason
        CHECK (match_reason IS NULL OR match_reason IN (
            'FAVORITE_STORE',
            'FAVORITE_ITEM',
            'NEARBY_AREA',
            'BIG_DISCOUNT'
        ))
);

CREATE INDEX idx_notifications_recipient_created
    ON notifications (recipient_user_id, created_at DESC);

CREATE INDEX idx_notifications_recipient_unread
    ON notifications (recipient_user_id, created_at DESC)
    WHERE read_at IS NULL;

CREATE INDEX idx_user_roles_role_user
    ON user_roles (role, user_id);
