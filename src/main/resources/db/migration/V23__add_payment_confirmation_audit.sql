WHERE payment_status = 'REVIEW_REQUIRED';

UPDATE customer_orders
SET payment_confirmed_at = COALESCE(finalized_at, created_at)
WHERE payment_status = 'CONFIRMED';

ALTER TABLE customer_orders
    ADD CONSTRAINT fk_orders_payment_confirmed_by
        FOREIGN KEY (payment_confirmed_by_user_id) REFERENCES users(id),
    ADD CONSTRAINT chk_orders_payment_audit CHECK (
        (
            payment_status = 'UNPAID'
            AND payment_reported_at IS NULL
            AND payment_confirmed_at IS NULL
            AND payment_confirmed_by_user_id IS NULL
        )
        OR (
            payment_status = 'REVIEW_REQUIRED'
            AND payment_reported_at IS NOT NULL
            AND payment_confirmed_at IS NULL
            AND payment_confirmed_by_user_id IS NULL
        )
        OR (
            payment_status = 'CONFIRMED'
            AND payment_confirmed_at IS NOT NULL
        )
    );

CREATE TABLE order_payment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,
    order_id BIGINT NOT NULL,
    actor_user_id BIGINT NOT NULL,
    event_type VARCHAR(32) NOT NULL,
    payment_method VARCHAR(24) NOT NULL,
    from_status VARCHAR(24) NOT NULL,
    to_status VARCHAR(24) NOT NULL,
    note VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_order_payment_events_public UNIQUE (public_id),
    CONSTRAINT fk_order_payment_events_order
        FOREIGN KEY (order_id) REFERENCES customer_orders(id),
    CONSTRAINT fk_order_payment_events_actor
        FOREIGN KEY (actor_user_id) REFERENCES users(id),
    CONSTRAINT chk_order_payment_events_type CHECK (
        event_type IN (
            'TRANSFER_REPORTED',
            'PAYMENT_CONFIRMED',
            'PAYMENT_REJECTED',
            'CASH_COLLECTED'
        )
    ),
    CONSTRAINT chk_order_payment_events_method CHECK (
        payment_method IN ('BANK_TRANSFER', 'CASH')
    ),
    CONSTRAINT chk_order_payment_events_from_status CHECK (
        from_status IN ('UNPAID', 'CONFIRMED', 'REVIEW_REQUIRED')
    ),
    CONSTRAINT chk_order_payment_events_to_status CHECK (
        to_status IN ('UNPAID', 'CONFIRMED', 'REVIEW_REQUIRED')
    ),
    CONSTRAINT chk_order_payment_events_rejection_note CHECK (
        event_type <> 'PAYMENT_REJECTED'
        OR (note IS NOT NULL AND LENGTH(TRIM(note)) > 0)
    )
);

CREATE INDEX idx_order_payment_events_order_created
    ON order_payment_events(order_id, created_at DESC, id DESC);
