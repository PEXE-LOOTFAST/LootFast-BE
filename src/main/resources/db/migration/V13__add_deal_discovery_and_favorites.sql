CREATE TABLE user_favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    favorite_type VARCHAR(16) NOT NULL,
    deal_id BIGINT,
    merchant_profile_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_user_favorites_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_favorites_deal
        FOREIGN KEY (deal_id) REFERENCES deals(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_favorites_store
        FOREIGN KEY (merchant_profile_id) REFERENCES merchant_profiles(id) ON DELETE CASCADE,
    CONSTRAINT uk_user_favorites_deal UNIQUE (user_id, deal_id),
    CONSTRAINT uk_user_favorites_store UNIQUE (user_id, merchant_profile_id),
    CONSTRAINT chk_user_favorites_target CHECK (
        (favorite_type = 'DEAL' AND deal_id IS NOT NULL AND merchant_profile_id IS NULL)
        OR
        (favorite_type = 'STORE' AND deal_id IS NULL AND merchant_profile_id IS NOT NULL)
    )
);

CREATE INDEX idx_user_favorites_page
    ON user_favorites (user_id, created_at DESC, id DESC);
