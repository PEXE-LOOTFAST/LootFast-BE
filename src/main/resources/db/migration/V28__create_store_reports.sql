-- FR-CU-15: khách báo cáo cửa hàng (hết hàng, sai mô tả, đóng cửa sớm...) kèm minh chứng.
-- Báo cáo luôn gắn với một đơn của chính khách để chống report khống.
CREATE TABLE store_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,
    reporter_id BIGINT NOT NULL REFERENCES users(id),
    merchant_profile_id BIGINT NOT NULL REFERENCES merchant_profiles(id),
    order_id BIGINT NOT NULL REFERENCES customer_orders(id),
    report_type VARCHAR(24) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    evidence_image_url VARCHAR(2048),
    evidence_storage_key VARCHAR(255),
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_store_reports_public UNIQUE (public_id),
    -- Một khách chỉ gửi được một báo cáo cùng loại cho cùng một đơn.
    CONSTRAINT uk_store_reports_order_reporter_type UNIQUE (order_id, reporter_id, report_type)
);

-- Liệt kê báo cáo của một khách, mới nhất trước.
CREATE INDEX idx_store_reports_reporter ON store_reports (reporter_id, created_at DESC);

-- Phục vụ 068: đếm báo hết hàng của một cửa hàng trong cửa sổ thời gian.
CREATE INDEX idx_store_reports_merchant_type_time
    ON store_reports (merchant_profile_id, report_type, created_at);
