UPDATE deals d
SET total_quantity = d.remaining_quantity + COALESCE((
    SELECT SUM(o.quantity)
    FROM customer_orders o
    WHERE o.deal_id = d.id
      AND o.status IN ('RESERVED', 'COMPLETED')
), 0);

