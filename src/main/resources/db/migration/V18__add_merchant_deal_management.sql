    ADD CONSTRAINT chk_deals_quantity
        CHECK (
            total_quantity BETWEEN 0 AND 10000
            AND remaining_quantity BETWEEN 0 AND total_quantity
        );

CREATE TABLE deal_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,
    deal_id BIGINT NOT NULL,
    storage_key VARCHAR(255),
    image_url VARCHAR(2048) NOT NULL,
    display_order INTEGER NOT NULL,
    status VARCHAR(16) NOT NULL,
    removed_at TIMESTAMP WITH TIME ZONE,
    removed_by_user_id BIGINT,
    removal_reason VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_deal_images_public_id UNIQUE (public_id),
    CONSTRAINT fk_deal_images_deal
        FOREIGN KEY (deal_id) REFERENCES deals(id) ON DELETE CASCADE,
    CONSTRAINT fk_deal_images_removed_by
        FOREIGN KEY (removed_by_user_id) REFERENCES users(id),
    CONSTRAINT chk_deal_images_display_order CHECK (display_order >= 0),
    CONSTRAINT chk_deal_images_status CHECK (status IN ('ACTIVE', 'REMOVED')),
    CONSTRAINT chk_deal_images_removal CHECK (
        (status = 'ACTIVE' AND removed_at IS NULL AND removed_by_user_id IS NULL AND removal_reason IS NULL)
        OR
        (status = 'REMOVED' AND removed_at IS NOT NULL AND removed_by_user_id IS NOT NULL AND removal_reason IS NOT NULL)
    )
);

INSERT INTO deal_images (
    public_id,
    deal_id,
    storage_key,
    image_url,
    display_order,
    status,
    created_at
)
SELECT
    gen_random_uuid(),
    id,
    NULL,
    primary_image_url,
    0,
    'ACTIVE',
    created_at
FROM deals
WHERE primary_image_url IS NOT NULL;

CREATE INDEX idx_deal_images_active_order
    ON deal_images (deal_id, status, display_order, id);

