-- FR-TR-05: Admin cảnh cáo hoặc đình chỉ cửa hàng vi phạm, kèm lý do và thời hạn.
-- Lịch sử xử phạt bất biến (append-only) trong merchant_sanctions; cột suspended_until trên
-- merchant_profiles là bản denormalize để feed/tạo deal lọc nhanh "đang bị đình chỉ".
ALTER TABLE merchant_profiles
    ADD COLUMN suspended_until TIMESTAMPTZ;

CREATE TABLE merchant_sanctions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,
    merchant_profile_id BIGINT NOT NULL REFERENCES merchant_profiles(id),
    sanction_type VARCHAR(16) NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    created_by_user_id BIGINT NOT NULL REFERENCES users(id),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ,
    lifted_at TIMESTAMPTZ,
    lifted_by_user_id BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_merchant_sanctions_public UNIQUE (public_id)
);

CREATE INDEX idx_merchant_sanctions_merchant
    ON merchant_sanctions (merchant_profile_id, created_at DESC);
