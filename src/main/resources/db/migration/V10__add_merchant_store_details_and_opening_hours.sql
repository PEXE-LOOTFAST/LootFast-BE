ALTER TABLE merchant_profiles
    ADD COLUMN store_name VARCHAR(120),
    ADD COLUMN description VARCHAR(1000),
    ADD COLUMN business_category VARCHAR(100),
    ADD COLUMN contact_email VARCHAR(254),
    ADD COLUMN contact_phone VARCHAR(16),
    ADD COLUMN address_line VARCHAR(255),
    ADD COLUMN ward VARCHAR(100),
    ADD COLUMN district VARCHAR(100),
    ADD COLUMN city VARCHAR(100),
    ADD COLUMN latitude NUMERIC(9, 6),
    ADD COLUMN longitude NUMERIC(9, 6),
    ADD CONSTRAINT ck_merchant_profiles_coordinates
        CHECK (
            (latitude IS NULL AND longitude IS NULL)
            OR (
                latitude BETWEEN -90 AND 90
                AND longitude BETWEEN -180 AND 180
            )
        );

CREATE TABLE merchant_opening_hours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_profile_id BIGINT NOT NULL,
    day_of_week VARCHAR(9) NOT NULL,
    opens_at TIME NOT NULL,
    closes_at TIME NOT NULL,
    CONSTRAINT fk_merchant_opening_hours_profile
        FOREIGN KEY (merchant_profile_id) REFERENCES merchant_profiles(id) ON DELETE CASCADE,
    CONSTRAINT uk_merchant_opening_hours_slot
        UNIQUE (merchant_profile_id, day_of_week, opens_at, closes_at),
    CONSTRAINT ck_merchant_opening_hours_day
        CHECK (day_of_week IN (
            'MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY',
            'FRIDAY', 'SATURDAY', 'SUNDAY'
        )),
    CONSTRAINT ck_merchant_opening_hours_range CHECK (opens_at < closes_at)
);

CREATE INDEX idx_merchant_opening_hours_profile_day
    ON merchant_opening_hours (merchant_profile_id, day_of_week, opens_at);
