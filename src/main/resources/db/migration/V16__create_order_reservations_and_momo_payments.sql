CREATE TABLE customer_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,
    buyer_id BIGINT NOT NULL REFERENCES users(id),
    merchant_profile_id BIGINT NOT NULL REFERENCES merchant_profiles(id),
    deal_id BIGINT NOT NULL REFERENCES deals(id),
    deal_name VARCHAR(160) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 5),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price > 0),
    total_amount NUMERIC(14,2) NOT NULL CHECK (total_amount = unit_price * quantity),
    pickup_start TIMESTAMP WITH TIME ZONE NOT NULL,
    pickup_end TIMESTAMP WITH TIME ZONE NOT NULL CHECK (pickup_end > pickup_start),
    status VARCHAR(24) NOT NULL CHECK (status IN ('RESERVED','COMPLETED','CANCELLED','NO_SHOW','MERCHANT_CANCELLED')),
    payment_method VARCHAR(24) NOT NULL CHECK (payment_method IN ('BANK_TRANSFER','MOMO','CASH')),
    payment_status VARCHAR(24) NOT NULL CHECK (payment_status IN ('UNPAID','CONFIRMED','REVIEW_REQUIRED')),
    payment_reference VARCHAR(23) NOT NULL,
    reservation_key UUID NOT NULL,
    request_fingerprint VARCHAR(200) NOT NULL,
    replay_until TIMESTAMP WITH TIME ZONE NOT NULL,
    creation_response TEXT NOT NULL,
    bank_bin VARCHAR(6),
    bank_name VARCHAR(100),
    bank_account_number VARCHAR(19),
    bank_holder_name VARCHAR(120),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_orders_public UNIQUE (public_id),
    CONSTRAINT uk_orders_key UNIQUE (buyer_id,reservation_key),
    CONSTRAINT uk_orders_reference UNIQUE (payment_reference),
    CONSTRAINT chk_order_bank_snapshot CHECK (
        (bank_bin IS NULL AND bank_name IS NULL AND bank_account_number IS NULL AND bank_holder_name IS NULL)
        OR (bank_bin IS NOT NULL AND bank_name IS NOT NULL AND bank_account_number IS NOT NULL AND bank_holder_name IS NOT NULL))
);
-- Full indexes support count queries and future status transitions on all database engines.
CREATE INDEX idx_orders_buyer_status ON customer_orders(buyer_id,status);
CREATE INDEX idx_orders_buyer_deal_status ON customer_orders(buyer_id,deal_id,status);
CREATE INDEX idx_orders_merchant_status ON customer_orders(merchant_profile_id,status);
CREATE INDEX idx_orders_deal ON customer_orders(deal_id);
CREATE TABLE momo_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES customer_orders(id),
    provider_order_id VARCHAR(50) NOT NULL UNIQUE,
    request_id VARCHAR(50) NOT NULL,
    partner_code VARCHAR(50) NOT NULL,
    amount BIGINT NOT NULL CHECK (amount BETWEEN 1000 AND 50000000),
    state VARCHAR(24) NOT NULL CHECK (state IN ('UNKNOWN','PENDING','SUCCEEDED','FAILED','REVIEW_REQUIRED')),
    pay_url VARCHAR(2048),
    deeplink VARCHAR(4096),
    qr_payload VARCHAR(4096),
    trans_id BIGINT UNIQUE,
    last_requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_momo_payments_order ON momo_payments(order_id,id DESC);
