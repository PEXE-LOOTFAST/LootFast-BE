CREATE TABLE notification_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    matching_deals_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    buyer_order_updates_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    merchant_order_updates_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    pickup_reminders_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    email_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_notification_preferences_user UNIQUE (user_id),
    CONSTRAINT fk_notification_preferences_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
