CREATE TABLE external_auth_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    provider VARCHAR(16) NOT NULL,
    provider_subject VARCHAR(255) NOT NULL,
    provider_email VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_external_auth_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uk_external_auth_provider_subject
        UNIQUE (provider, provider_subject),
    CONSTRAINT uk_external_auth_user_provider
        UNIQUE (user_id, provider)
);

CREATE INDEX idx_external_auth_user_id
    ON external_auth_identities (user_id);

CREATE TABLE user_consents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    document VARCHAR(32) NOT NULL,
    document_version VARCHAR(50) NOT NULL,
    accepted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_user_consents_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uk_user_consents_user_document_version
        UNIQUE (user_id, document, document_version)
);

CREATE INDEX idx_user_consents_user_id
    ON user_consents (user_id);

CREATE INDEX idx_merchant_profiles_coordinates
    ON merchant_profiles (latitude, longitude)
    WHERE latitude IS NOT NULL AND longitude IS NOT NULL;

CREATE TABLE deals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,
    merchant_profile_id BIGINT NOT NULL,
    name VARCHAR(160) NOT NULL,
    category_code VARCHAR(100) NOT NULL,
    original_price NUMERIC(12, 2) NOT NULL,
    discounted_price NUMERIC(12, 2) NOT NULL,
    remaining_quantity INTEGER NOT NULL,
    primary_image_url VARCHAR(2048) NOT NULL,
    preparation_minutes INTEGER NOT NULL,
    pickup_start TIMESTAMP WITH TIME ZONE NOT NULL,
    pickup_end TIMESTAMP WITH TIME ZONE NOT NULL,
    available_from TIMESTAMP WITH TIME ZONE NOT NULL,
    available_until TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(24) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_deals_public_id UNIQUE (public_id),
    CONSTRAINT fk_deals_merchant_profile
        FOREIGN KEY (merchant_profile_id) REFERENCES merchant_profiles(id) ON DELETE CASCADE,
    CONSTRAINT chk_deals_prices
        CHECK (original_price > 0 AND discounted_price > 0
            AND discounted_price <= original_price * 0.90),
    CONSTRAINT chk_deals_quantity CHECK (remaining_quantity >= 0),
    CONSTRAINT chk_deals_preparation CHECK (preparation_minutes >= 0),
    CONSTRAINT chk_deals_pickup_window CHECK (pickup_end > pickup_start),
    CONSTRAINT chk_deals_availability_window CHECK (available_until > available_from)
);

CREATE INDEX idx_deals_feed
    ON deals (status, available_from, available_until);
CREATE INDEX idx_deals_merchant_id
    ON deals (merchant_profile_id);
