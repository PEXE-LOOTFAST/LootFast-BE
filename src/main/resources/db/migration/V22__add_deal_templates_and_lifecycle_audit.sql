-- Deal removal is a soft lifecycle transition. Existing orders continue to reference the deal,
-- while their immutable snapshots preserve the name, prices and pickup window shown at checkout.
ALTER TABLE deals
    ADD COLUMN hidden_at TIMESTAMP WITH TIME ZONE,
    ADD COLUMN removed_at TIMESTAMP WITH TIME ZONE,
    ADD COLUMN removed_by_user_id BIGINT,
    ADD COLUMN removal_reason VARCHAR(500);

UPDATE deals
SET hidden_at = updated_at
WHERE status = 'HIDDEN';

UPDATE deals
SET removed_at = updated_at,
    removal_reason = 'Removed before lifecycle audit was introduced'
WHERE status = 'REMOVED';

ALTER TABLE deals
    ADD CONSTRAINT fk_deals_removed_by
        FOREIGN KEY (removed_by_user_id) REFERENCES users(id),
    ADD CONSTRAINT chk_deals_hidden_metadata CHECK (
        (status = 'HIDDEN' AND hidden_at IS NOT NULL)
        OR (status <> 'HIDDEN' AND hidden_at IS NULL)
    ),
    ADD CONSTRAINT chk_deals_removed_metadata CHECK (
        (status = 'REMOVED' AND removed_at IS NOT NULL AND removal_reason IS NOT NULL)
        OR (
            status <> 'REMOVED'
            AND removed_at IS NULL
            AND removed_by_user_id IS NULL
            AND removal_reason IS NULL
        )
    );

CREATE TABLE deal_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,
    merchant_profile_id BIGINT NOT NULL,
    source_deal_id BIGINT,
    name VARCHAR(160) NOT NULL,
    category_code VARCHAR(100) NOT NULL,
    original_price NUMERIC(12,2) NOT NULL,
    discounted_price NUMERIC(12,2) NOT NULL,
    default_quantity INTEGER NOT NULL,
    preparation_minutes INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_deal_templates_public UNIQUE (public_id),
    CONSTRAINT fk_deal_templates_merchant
        FOREIGN KEY (merchant_profile_id) REFERENCES merchant_profiles(id) ON DELETE CASCADE,
    CONSTRAINT fk_deal_templates_source
        FOREIGN KEY (source_deal_id) REFERENCES deals(id) ON DELETE SET NULL,
    CONSTRAINT chk_deal_templates_prices CHECK (
        original_price > 0
        AND discounted_price > 0
        AND discounted_price * 100 <= original_price * 90
    ),
    CONSTRAINT chk_deal_templates_quantity CHECK (default_quantity BETWEEN 0 AND 10000),
    CONSTRAINT chk_deal_templates_preparation CHECK (preparation_minutes BETWEEN 0 AND 1440)
);

CREATE INDEX idx_deal_templates_merchant_created
    ON deal_templates(merchant_profile_id, created_at DESC, id DESC);
