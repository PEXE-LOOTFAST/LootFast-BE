CREATE TABLE store_reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_id UUID NOT NULL UNIQUE,
 order_id BIGINT NOT NULL UNIQUE REFERENCES customer_orders(id),
 buyer_id BIGINT NOT NULL REFERENCES users(id),
 merchant_id BIGINT NOT NULL REFERENCES merchant_profiles(id),
 rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
 comment VARCHAR(1000),
 created_at TIMESTAMPTZ NOT NULL,
 reply VARCHAR(1000),
 replied_at TIMESTAMPTZ,
 hidden BOOLEAN NOT NULL DEFAULT FALSE,
 CHECK ((reply IS NULL AND replied_at IS NULL) OR (reply IS NOT NULL AND replied_at IS NOT NULL))
);
CREATE INDEX idx_store_reviews_public ON store_reviews(merchant_id, created_at DESC, id DESC) WHERE hidden = FALSE;
CREATE INDEX idx_store_reviews_merchant ON store_reviews(merchant_id, created_at DESC, id DESC);
CREATE INDEX idx_store_reviews_created ON store_reviews(created_at DESC, id DESC);
CREATE TABLE review_moderation_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 review_id BIGINT NOT NULL REFERENCES store_reviews(id),
 admin_id BIGINT NOT NULL REFERENCES users(id),
 hidden BOOLEAN NOT NULL,
 reason VARCHAR(1000) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_review_moderation_history ON review_moderation_events(review_id, created_at DESC, id DESC);
