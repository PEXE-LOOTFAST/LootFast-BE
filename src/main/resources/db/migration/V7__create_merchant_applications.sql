CREATE TABLE merchant_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,
    user_id BIGINT NOT NULL,
    business_license_number VARCHAR(14) NOT NULL,
    license_storage_key VARCHAR(255),
    license_format VARCHAR(16),
    submission_id UUID NOT NULL,
    status VARCHAR(32) NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    reviewed_by_user_id BIGINT,
    rejection_reason VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_merchant_applications_public_id UNIQUE (public_id),
    CONSTRAINT uk_merchant_applications_user_id UNIQUE (user_id),
    CONSTRAINT fk_merchant_applications_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_merchant_applications_reviewer
        FOREIGN KEY (reviewed_by_user_id) REFERENCES users(id)
);

CREATE INDEX idx_merchant_applications_status_submitted
    ON merchant_applications (status, submitted_at);
