-- FR-TR-03 / FR-TR-04 / FR-AD-04: trung tâm ticket hỗ trợ & tranh chấp.
-- support_tickets giữ ticket hiện tại; ticket_events là log bất biến (append-only) mọi thao tác.
CREATE TABLE support_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,
    reporter_id BIGINT REFERENCES users(id),            -- null khi hệ thống tự mở (045)
    origin VARCHAR(16) NOT NULL,
    category VARCHAR(24) NOT NULL,
    order_id BIGINT REFERENCES customer_orders(id),
    merchant_profile_id BIGINT REFERENCES merchant_profiles(id),
    title VARCHAR(160) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    evidence_image_url VARCHAR(2048),
    evidence_storage_key VARCHAR(255),
    status VARCHAR(16) NOT NULL,
    resolution_note VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_support_tickets_public UNIQUE (public_id)
);

CREATE INDEX idx_support_tickets_reporter ON support_tickets (reporter_id, created_at DESC);
CREATE INDEX idx_support_tickets_status ON support_tickets (status, created_at DESC);
CREATE INDEX idx_support_tickets_order ON support_tickets (order_id);

CREATE TABLE ticket_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES support_tickets(id),
    actor_user_id BIGINT REFERENCES users(id),          -- null khi hệ thống thao tác
    action VARCHAR(24) NOT NULL,
    note VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_ticket_events_ticket ON ticket_events (ticket_id, created_at);
