-- Merchant payout account used to build the VietQR string (FR-ME-03, BR-PAY-02).
-- Kept in its own table (not columns on merchant_profiles) because it is
-- payment-sensitive, has its own update rules (BR-PAY-07) and audit timestamps,
-- and gives the VietQR generator a self-contained account object.
CREATE TABLE merchant_bank_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_profile_id BIGINT NOT NULL,
    -- 6-digit NAPAS acquirer BIN: the canonical bank id required by VietQR.
    bank_bin VARCHAR(6) NOT NULL,
    bank_name VARCHAR(100) NOT NULL,
    account_number VARCHAR(19) NOT NULL,
    account_holder_name VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    -- One account per store (1 tài khoản — 1 cửa hàng).
    CONSTRAINT uk_merchant_bank_accounts_merchant UNIQUE (merchant_profile_id),
    CONSTRAINT fk_merchant_bank_accounts_merchant
        FOREIGN KEY (merchant_profile_id) REFERENCES merchant_profiles(id) ON DELETE CASCADE
);
